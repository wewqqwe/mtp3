"""Допуск пополнения и списания до изменения остатка."""

from __future__ import annotations


def accept_deposit(amount: int) -> None:
    """Отклоняет пополнение отрицательной суммой."""
    if amount < 0:
        raise ValueError("Пополнение на отрицательную сумму отклонено.")


def accept_withdrawal(balance: int, amount: int) -> None:
    """Отклоняет списание, если остаток стал бы отрицательным.

    Решение принимается до записи, поэтому отказ не меняет баланс.
    Отрицательная сумма списания также не принимается.
    """
    if amount < 0:
        raise ValueError("Списание отрицательной суммы отклонено.")
    if balance - amount < 0:
        raise ValueError(
            "Списание отклонено: остаток стал бы отрицательным."
        )
